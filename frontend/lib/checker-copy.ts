/** Pick a supported language: explicit choice, then the browser's preference, else English. */
export function pickLang(choice?: string | null, acceptLanguage?: string | null): Lang {
  if (choice === "en" || choice === "es" || choice === "ar") return choice
  for (const part of (acceptLanguage ?? "").split(",")) {
    const code = part.trim().slice(0, 2).toLowerCase()
    if (code === "es" || code === "ar" || code === "en") return code
  }
  return "en"
}

